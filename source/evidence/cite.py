#!/usr/bin/env python3
"""Build src/refs.js (the app's evidence library) and the evidence-base markdown from refs_aster.py.
Citations and DOIs for PubMed entries come from records.json (PubMed records retrieved 21 November 2026);
nothing is typed in by hand for those. Usage: python3 cite.py [records.json] [out_dir]"""
import json, os, sys, importlib.util

HERE = os.path.dirname(os.path.abspath(__file__))
REC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "records.json")
ROOT = os.path.dirname(HERE)
spec = importlib.util.spec_from_file_location("refs", os.path.join(HERE, "refs_aster.py"))
mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
REFS = mod.REFS
recs = json.load(open(REC))

GR = {"strong": "STRONG", "mod": "MODERATE", "weak": "WEAK", "no": "NOT SUPPORTED", "": "—"}
TOPIC = {"guide": "Guidelines", "changes": "Hormone changes", "safety": "Safety and monitoring", "body": "Body and movement",
         "binding": "Binding and tucking", "mind": "Mind and emotions", "social": "Social and legal", "surgery": "Surgery"}

def citation(r):
    au = r.get("authors3") or []
    n = r.get("n_authors", len(au))
    a = ", ".join(au) + (", et al" if n > 3 else "")
    t = (r.get("title") or "").rstrip(".")
    jn = r.get("journal", "")
    vol, iss, pg = r.get("volume", ""), r.get("issue", ""), r.get("pages", "")
    tail = f"{r.get('year','')}"
    if vol: tail += f";{vol}"
    if iss: tail += f"({iss})"
    if pg: tail += f":{pg}"
    return f"{a}. {t}. {jn}. {tail}.".replace("..", ".").lstrip(". ")

out = {}
problems = []
for rid, e in REFS.items():
    o = {"s": e["s"], "k": e["k"], "g": e["g"], "t": e["t"], "pop": e["pop"], "f": e["f"]}
    if e.get("pmid"):
        r = recs.get(e["pmid"])
        if not r:
            problems.append(f"{rid}: PMID {e['pmid']} not in records"); continue
        o["p"] = e["pmid"]; o["c"] = citation(r)
        if r.get("doi"): o["d"] = r["doi"]
        o["y"] = r.get("year", "")
    else:
        o["c"] = e["c"]
        if e.get("url"): o["u"] = e["url"]
        if e.get("doi"): o["d"] = e["doi"]
    out[rid] = o

if problems:
    print("\n".join(problems)); sys.exit(1)

js = "// Evidence library. Generated by evidence/cite.py from PubMed-verified records; do not edit by hand.\nconst REFS = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n"
open(os.path.join(ROOT, "src", "refs.js"), "w", encoding="utf-8").write(js)

# Markdown evidence base, grouped by topic
lines = ["# Aster evidence base", "",
         "Every source used in *Aster*, grouped by topic, with who was studied, what was found and how strong the evidence is. "
         "PubMed records (titles, authors, journals and DOIs) were retrieved and checked on 21 November 2026; government and service pages were checked on the same day.", "",
         "**Grades.** STRONG: consistent results from randomised trials or very large, well-conducted studies; unlikely to change. "
         "MODERATE: good evidence with limits, such as consistent prospective cohort studies; could change. "
         "WEAK: small, early or indirect evidence, such as one-off (cross-sectional) surveys, case series and reviews that pool them, or studies in a different group. "
         "NOT SUPPORTED: tested and not shown, or the original claim did not hold up. A dash means a guideline, law or service page, which is not graded. "
         "In the app, practical advice from clinicians' and community experience where no study exists is labelled \"clinical consensus\" rather than graded.", "",
         "An independent reviewer then checked every claim in the app against these sources on 21 November 2026; the findings and corrections are in *Aster fact-check report*.", ""]
for t, tname in TOPIC.items():
    ids = [k for k, v in out.items() if v["t"] == t]
    if not ids: continue
    lines += [f"## {tname}", ""]
    for k in ids:
        v = out[k]
        ref = []
        if v.get("p"): ref.append(f"PMID [{v['p']}](https://pubmed.ncbi.nlm.nih.gov/{v['p']}/)")
        if v.get("d"): ref.append(f"DOI [{v['d']}](https://doi.org/{v['d']})")
        if v.get("u"): ref.append(f"[Source]({v['u']})")
        lines += [f"**{v['s']}** · {v['k']} · {GR[v['g']]}  ",
                  f"{v['c']}  ", f"*Who:* {v['pop']}  ", f"*Found:* {v['f']}  ", " · ".join(ref), ""]
md = "\n".join(lines) + "\n"
open(os.path.join(ROOT, "Aster evidence base.md"), "w", encoding="utf-8").write(md)
print(f"{len(out)} sources -> src/refs.js and Aster evidence base.md")
