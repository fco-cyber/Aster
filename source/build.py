def icon(name, cls="i"):
    return (f'<svg class="{cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" '
            f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{ICONS[name]}</svg>')
MARK = ('<svg class="mark" viewBox="-18 -18 36 36" aria-hidden="true" focusable="false"><g class="mk-p">' +
        "".join(f'<ellipse cx="0" cy="-9.2" rx="2.7" ry="7" transform="rotate({k*36})"/>' for k in range(10)) +
        '</g><circle r="4.8" class="mk-c"/></svg>')
def icons_in(html):
    html = html.replace("__MARK__", MARK)
    return re.sub(r"__I_([a-z]+)__", lambda m: icon(m.group(1)), html)

CSS_ORDER = ["palettes.css", "aster.css", "app.css"]
JS_ORDER = ["data.js", "@refs", "core.js", "ui.js", "figure.data.js", "figure.js", "changes.js", "journey.js", "bloom.js", "diagrams.js", "recovery.js", "boot.js"]

def build(out=OUT, head_extra="", tail_extra=""):
    shell = rd("shell.html")
    views = "".join(rd(os.path.join("views", f)) for f in sorted(os.listdir(os.path.join(SRC, "views"))) if f.endswith(".html"))
    refs = rd("refs.js").replace("export const REFS", "const REFS")
    nrefs = len(re.findall(r'^"[A-Z0-9]+":', refs, re.M))
    views = views.replace("__NREFS__", str(nrefs))
    css = fonts_css() + "\n" + "\n".join(rd(f) for f in CSS_ORDER)
    pals = open(os.path.join(SRC, "pals.json")).read().strip()
    parts = []
    for f in JS_ORDER:
        if f == "@refs": parts.append(refs); continue
        js = rd(os.path.join("js", f))
        if f == "data.js": js = js.replace("/*PALS*/[]", pals).replace("/*ICONS*/{}", json.dumps(ICONS))
        parts.append("/* ===== " + f + " ===== */\n" + js)
    script = "<script>\n(function(){\n" + "\n".join(parts) + "\n})();\n</script>"
    icon = "data:image/svg+xml," + urllib.parse.quote(ICON_SVG, safe=":/=,;'\" ")
    shell = icons_in(shell); views = icons_in(views)
    html = (shell.replace("<!--HEAD-SCRIPT-->", HEAD_SCRIPT)
                 .replace("<!--STYLE-->", "<style>\n" + css + "\n</style>")
                 .replace("<!--VIEWS-->", views)
                 .replace("<!--SCRIPT-->", script + tail_extra)
                 .replace("<!--HEAD-EXTRA-->", head_extra)
                 .replace("__ICON__", icon))
    # the first view is shown before the script runs, so the page isn't blank if scripts are blocked
    html = html.replace('<section class="view" id="v-home"', '<section class="view on" id="v-home"', 1)
    left = [m for m in re.findall(r"<!--[A-Z-]+-->", html)]
    assert not left, left
    assert "__NREFS__" not in html and "/*PALS*/" not in html and "/*ICONS*/" not in html and "__I_" not in html and "__MARK__" not in html
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write(html)
    return out, len(html.encode("utf-8")), nrefs

if __name__ == "__main__":
    o, n, nr = build()
    print("built", o, round(n / 1024), "KB,", nr, "sources")
