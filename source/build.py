"""Build Aster into one self-contained HTML file.
   src/shell.html      page skeleton with <!--...--> slots and __I_name__ icon slots
   src/palettes.css    four palettes, light and dark (tools/palettes.py); src/aster.css the design system;
   src/app.css         Aster's diagrams, tools and interactive components
   src/views/*.html    one file per page, in order
   src/refs.js         evidence library, generated by evidence/cite.py
   src/js/*.js         modules, concatenated in a fixed order inside one closure
Usage: python3 build.py [out.html]"""
import json, re, sys, os, urllib.parse
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")
FONTS = os.path.join(HERE, "fonts")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "out", "Aster v1.html")
rd = lambda p: open(os.path.join(SRC, p), encoding="utf-8").read()

def fonts_css():
    meta = json.load(open(os.path.join(FONTS, "fonts.json")))
    out = ["/* Embedded open-licence fonts (SIL Open Font License 1.1): Bricolage Grotesque and Figtree, so the guide looks the same offline and makes no third-party requests. */"]
    for f in meta:
        b64 = open(os.path.join(FONTS, f["file"] + ".b64")).read().strip()
        stretch = ("font-stretch:%s;" % f["stretch"]) if f.get("stretch") else ""
        out.append('@font-face{font-family:"%s";font-style:%s;font-weight:%s;%sfont-display:swap;src:url(data:font/woff2;base64,%s) format("woff2");unicode-range:%s}' % (f["family"], f["style"], f["weight"], stretch, b64, f["range"]))
    return "\n".join(out)

